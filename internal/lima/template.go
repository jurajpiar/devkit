package lima

import (
	"bytes"
	"fmt"
	"strings"
	"text/template"

	"github.com/jurajpiar/devkit/internal/project"
	"github.com/jurajpiar/devkit/internal/provision"
)

// TemplateInput is everything needed to render a Lima instance config.
type TemplateInput struct {
	Config *project.Config
	// User is the macOS username; Lima creates the same account in the guest.
	User string
	// HostDir is the project directory on the host, used for source: mount.
	HostDir string
	// EgressSHA256 is the hash of the proxy binary the host will drop in.
	EgressSHA256 string
}

// Image is the guest base image: Ubuntu Minimal cloud image, pinned by
// release and digest. systemd, glibc, cloud-init and apt in ~220 MB.
// Bump deliberately: update the release path and both digests together from
// https://cloud-images.ubuntu.com/minimal/releases/noble/<release>/SHA256SUMS
const (
	ImageRelease  = "release-20261001"
	ImageBaseURL  = "https://cloud-images.ubuntu.com/minimal/releases/noble/" + ImageRelease
	ImageArm64    = ImageBaseURL + "/ubuntu-24.04-minimal-cloudimg-arm64.img"
	ImageArm64SHA = "sha256:fbf6b15c50c474dc6dee5b3c74da212bb687a2625e877227828e6492d88dc151"
	ImageAmd64    = ImageBaseURL + "/ubuntu-24.04-minimal-cloudimg-amd64.img"
	ImageAmd64SHA = "sha256:a8eb6570f87a941f3de2e000c046b9367f8ab1423756a94830d454fae8ad80ff"
)

const limaTmpl = `# Generated by devkit for project "{{.Config.Name}}". Edit devkit.yaml instead.
minimumLimaVersion: 1.1.0

# Ubuntu Minimal cloud image, pinned by digest. See internal/lima/template.go.
images:
  - location: "{{.ImageArm64}}"
    arch: "aarch64"
    digest: "{{.ImageArm64SHA}}"
  - location: "{{.ImageAmd64}}"
    arch: "x86_64"
    digest: "{{.ImageAmd64SHA}}"

# Apple Virtualization.framework is the only supported hypervisor.
vmType: vz
cpus: {{.Config.VM.CPUs}}
memory: "{{.Config.VM.MemoryGB}}GiB"
disk: "{{.Config.VM.DiskGB}}GiB"

# No host filesystem unless source: mount is chosen explicitly.
mountType: virtiofs
{{- if eq .Config.Source "mount"}}
mounts:
  - location: {{printf "%q" .HostDir}}
    writable: {{.Config.MountWritable}}
{{- else}}
mounts: []
{{- end}}

# Rootless containers inside the VM are opt-in.
containerd:
  system: false
  user: {{.Config.Tools.Containers}}

ssh:
  localPort: {{.Config.SSHPort}}
  loadDotSSHPubKeys: true

provision:
  - mode: system
    script: |
{{indent 6 .SystemScript}}
  - mode: user
    script: |
{{indent 6 .UserScript}}
`

// Render produces the lima.yaml for a project.
func Render(in TemplateInput) (string, error) {
	params := provision.Params{
		Config:       in.Config,
		User:         in.User,
		EgressSHA256: in.EgressSHA256,
		MountPath:    in.HostDir,
	}
	sys, err := provision.System(params)
	if err != nil {
		return "", err
	}
	usr, err := provision.User(params)
	if err != nil {
		return "", err
	}

	t, err := template.New("lima").Funcs(template.FuncMap{
		"indent": func(n int, s string) string {
			pad := strings.Repeat(" ", n)
			lines := strings.Split(strings.TrimRight(s, "\n"), "\n")
			for i, l := range lines {
				if l != "" {
					lines[i] = pad + l
				}
			}
			return strings.Join(lines, "\n")
		},
	}).Parse(limaTmpl)
	if err != nil {
		return "", fmt.Errorf("parse lima template: %w", err)
	}

	data := struct {
		TemplateInput
		SystemScript  string
		UserScript    string
		ImageArm64    string
		ImageArm64SHA string
		ImageAmd64    string
		ImageAmd64SHA string
	}{in, sys, usr, ImageArm64, ImageArm64SHA, ImageAmd64, ImageAmd64SHA}

	var buf bytes.Buffer
	if err := t.Execute(&buf, data); err != nil {
		return "", fmt.Errorf("render lima config: %w", err)
	}
	return buf.String(), nil
}
